def build_capability_document() -> dict:
    """能力验证数据集文档（独立版本/校验和，供评测中心建 Suite）。"""
    import hashlib
    import json as _json

    canon = _json.dumps({"version": CAPABILITY_VERSION, "cases": CAPABILITY_CASES},
                        ensure_ascii=False, sort_keys=True, indent=2)
    checksum = hashlib.sha256(canon.encode("utf-8")).hexdigest()
    return {
        "schema_version": "1.0",
        "dataset_version": CAPABILITY_VERSION,
        "checksum": checksum,
        "modalities": ["text"],
        "required_capabilities": ["refund_workflow", "security", "intent",
                                  "voice", "coaching"],
        "reserved_tags": [],           # 四能力在本数据集已实现（区别于 golden 预留段）
        "created_by": "eval_refund.capabilities_suite",
        "primary_owner": "customer_service1",
        "approver": "supervisor1",
        "case_count": len(CAPABILITY_CASES),
        "tiers": {"smoke": ["S01", "S06", "I01", "V01", "C01"],
                  "core": [c["id"] for c in CAPABILITY_CASES if c["id"] <= "I02"],
                  "full": [c["id"] for c in CAPABILITY_CASES]},
        "tier_labels": {"smoke": "冒烟：注入BLOCK+合法PASS+意图REFUND+语音打断+陪练评分",
                        "core": "核心：security+intent",
                        "full": "全量：四能力"},
        "cases": CAPABILITY_CASES,
        "dataset_checksum": checksum,
    }